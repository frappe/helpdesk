"""Seed and reset the synthetic test data for the team's API and browser tests.

Run with the bench's Python from the bench's `sites` directory (the wrapper
`tests/team/seed.sh` does this):

    python seed.py seed  [--site helpdesk.localhost]   # idempotent
    python seed.py reset [--site helpdesk.localhost]   # back to the seeded state

`seed` creates one agent and two customers, fixes the HD Settings the business
rules depend on, and writes the generated test passwords to tests/team/.env
(git-ignored). `reset` deletes every ticket the test accounts raised, together
with its communications and comments, and restores the settings. Nothing
outside the synthetic accounts is touched.
"""

import argparse
import secrets
from pathlib import Path

import frappe

TEAM_DIR = Path(__file__).resolve().parent.parent
ENV_FILE = TEAM_DIR / ".env"

AGENT = "agent.one@sqe.test"
CUSTOMER_A = "customer.a@sqe.test"
CUSTOMER_B = "customer.b@sqe.test"
ACCOUNTS = {
    "SQE_AGENT": (AGENT, "Asha", "Agent"),
    "SQE_CUSTOMER_A": (CUSTOMER_A, "Bilal", "Customer"),
    "SQE_CUSTOMER_B": (CUSTOMER_B, "Chen", "Customer"),
}

# The values the four business rules are tested against.
SETTINGS = {
    "auto_close_tickets": 1,  # BR1 on
    "auto_close_status": "Replied",  # BR1: tickets waiting on the customer
    "auto_close_after_days": 7,  # BR1: N
    "is_feedback_mandatory": 1,  # BR2
    "default_ticket_status": "Open",
    "ticket_reopen_status": "Open",
    "restrict_tickets_by_agent_group": 0,
}


# Records that hang off a ticket: doctype -> filter (None stands for the ticket name).
LINKED_RECORDS = {
    "Communication": {"reference_doctype": "HD Ticket", "reference_name": None},
    "Comment": {"reference_doctype": "HD Ticket", "reference_name": None},
    "ToDo": {"reference_type": "HD Ticket", "reference_name": None},
    "DocShare": {"share_doctype": "HD Ticket", "share_name": None},
    "HD Ticket Comment": {"reference_ticket": None},
    "HD Ticket Activity": {"ticket": None},
}


def read_env():
    values = {}
    if ENV_FILE.exists():
        for line in ENV_FILE.read_text().splitlines():
            if "=" in line and not line.startswith("#"):
                key, value = line.split("=", 1)
                values[key.strip()] = value.strip()
    return values


def write_env(values):
    lines = ["# Generated by tests/team/seed/seed.py. Local test values only."]
    lines += [f"{key}={value}" for key, value in sorted(values.items())]
    ENV_FILE.write_text("\n".join(lines) + "\n")
    ENV_FILE.chmod(0o600)


def ensure_user(email, first_name, last_name, password):
    if frappe.db.exists("User", email):
        user = frappe.get_doc("User", email)
    else:
        user = frappe.get_doc(
            {
                "doctype": "User",
                "email": email,
                "first_name": first_name,
                "last_name": last_name,
                "send_welcome_email": 0,
                "enabled": 1,
            }
        ).insert(ignore_permissions=True)
    user.new_password = password
    user.save(ignore_permissions=True)
    return user


def ensure_agent(email):
    if not frappe.db.exists("HD Agent", email):
        frappe.get_doc(
            {"doctype": "HD Agent", "user": email, "agent_name": "Asha Agent", "is_active": 1}
        ).insert(ignore_permissions=True)
    user = frappe.get_doc("User", email)
    user.add_roles("Agent")


def ensure_customer(email, first_name, last_name):
    user = frappe.get_doc("User", email)
    user.add_roles("HD Customer")
    if not frappe.db.exists("Contact", {"user": email}):
        frappe.get_doc(
            {
                "doctype": "Contact",
                "first_name": first_name,
                "last_name": last_name,
                "user": email,
                "email_ids": [{"email_id": email, "is_primary": 1}],
            }
        ).insert(ignore_permissions=True)


def apply_settings():
    settings = frappe.get_doc("HD Settings")
    for key, value in SETTINGS.items():
        settings.set(key, value)
    settings.save(ignore_permissions=True)


def seed(site):
    env = read_env()
    # Python's resolver does not map *.localhost to loopback on every platform,
    # so tests call 127.0.0.1 and send the site name in the Host header.
    env["SQE_BASE_URL"] = env.get("SQE_BASE_URL") or "http://127.0.0.1:8000"
    env["SQE_SITE"] = site
    for prefix, (email, first_name, last_name) in ACCOUNTS.items():
        password = env.get(f"{prefix}_PASSWORD") or secrets.token_urlsafe(12)
        ensure_user(email, first_name, last_name, password)
        env[f"{prefix}_EMAIL"] = email
        env[f"{prefix}_PASSWORD"] = password
    ensure_agent(AGENT)
    ensure_customer(CUSTOMER_A, "Bilal", "Customer")
    ensure_customer(CUSTOMER_B, "Chen", "Customer")
    apply_settings()
    frappe.db.commit()
    write_env(env)
    print(f"seeded: 1 agent, 2 customers, settings applied; test values in {ENV_FILE}")


def reset(site):
    emails = [email for email, _, _ in ACCOUNTS.values()]
    tickets = frappe.get_all(
        "HD Ticket", filters=[["raised_by", "in", emails]], pluck="name"
    ) + frappe.get_all("HD Ticket", filters=[["owner", "in", emails]], pluck="name")
    tickets = sorted(set(tickets))
    for name in tickets:
        for doctype, filters in LINKED_RECORDS.items():
            if not frappe.db.exists("DocType", doctype):
                continue
            meta = frappe.get_meta(doctype)
            if not all(meta.has_field(fieldname) for fieldname in filters):
                continue
            filters = {key: (name if value is None else value) for key, value in filters.items()}
            for child in frappe.get_all(doctype, filters=filters, pluck="name"):
                frappe.delete_doc(doctype, child, force=True, ignore_permissions=True, delete_permanently=True)
        frappe.delete_doc("HD Ticket", name, force=True, ignore_permissions=True, delete_permanently=True)
    apply_settings()
    frappe.db.commit()
    frappe.clear_cache()
    print(f"reset: removed {len(tickets)} test tickets and restored settings")


def agent_reply(ticket):
    """Record a sent agent reply on a ticket. The agent desk needs an outgoing
    mail account to do this; the test site has none, so browser tests call this."""
    raised_by = frappe.db.get_value("HD Ticket", ticket, "raised_by")
    frappe.get_doc(
        {
            "doctype": "Communication",
            "communication_type": "Communication",
            "communication_medium": "Email",
            "sent_or_received": "Sent",
            "reference_doctype": "HD Ticket",
            "reference_name": ticket,
            "subject": "Re: your ticket",
            "content": "<p>Please try restarting the printer.</p>",
            "sender": AGENT,
            "recipients": raised_by,
        }
    ).insert(ignore_permissions=True)
    frappe.db.commit()
    print(f"agent reply recorded on ticket {ticket}")


def set_setting(key, value):
    if key not in SETTINGS:
        raise SystemExit(f"only seeded settings may be changed: {sorted(SETTINGS)}")
    settings = frappe.get_doc("HD Settings")
    settings.set(key, int(value) if str(value).lstrip("-").isdigit() else value)
    settings.save(ignore_permissions=True)
    frappe.db.commit()
    print(f"HD Settings.{key} = {value}")


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("command", choices=["seed", "reset", "agent-reply", "setting"])
    parser.add_argument("--site", default="helpdesk.localhost")
    parser.add_argument("--ticket", help="agent-reply: the ticket that receives the reply")
    parser.add_argument("--key", help="setting: HD Settings field")
    parser.add_argument("--value", help="setting: new value")
    args = parser.parse_args()
    frappe.init(args.site)
    frappe.connect()
    frappe.set_user("Administrator")
    try:
        if args.command == "agent-reply":
            agent_reply(args.ticket)
        elif args.command == "setting":
            set_setting(args.key, args.value)
        else:
            {"seed": seed, "reset": reset}[args.command](args.site)
    finally:
        frappe.destroy()


if __name__ == "__main__":
    main()
