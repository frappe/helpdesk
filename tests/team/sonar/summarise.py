"""Summarise the exported SonarQube results into sonar/evidence/summary.md.

Usage: python summarise.py tests/team/sonar/evidence
"""

import collections
import json
import re
import sys
from pathlib import Path

RULE_FUNCTIONS = {  # file suffix -> functions the team's rules live in
    "hd_ticket.py": ["validate_feedback", "is_valid_status_transition",
                     "set_resolution_date", "close_tickets_after_n_days"],
    "customer_edit_controller.py": None,
    "hd_ticket_status.py": None,
}


def load(path):
    return json.loads(Path(path).read_text())


def measure_table(measures):
    values = {m["metric"]: m.get("value", m.get("period", {}).get("value", "")) for m in measures["component"]["measures"]}
    order = [
        ("Size", ["ncloc", "lines", "files", "functions", "classes", "statements", "comment_lines_density"]),
        ("Complexity", ["complexity", "cognitive_complexity"]),
        ("Issues", ["bugs", "vulnerabilities", "code_smells", "security_hotspots"]),
        ("Ratings (1=A ... 5=E)", ["reliability_rating", "security_rating", "sqale_rating", "security_review_rating"]),
        ("Technical debt", ["sqale_index", "sqale_debt_ratio"]),
        ("Duplication", ["duplicated_lines_density", "duplicated_blocks", "duplicated_lines"]),
        ("Coverage (unit suite)", ["coverage", "line_coverage", "branch_coverage", "lines_to_cover",
                                   "uncovered_lines", "conditions_to_cover", "uncovered_conditions"]),
        ("Tests", ["tests", "test_failures", "test_errors"]),
        ("Gate", ["alert_status"]),
    ]
    lines = ["| Group | Metric | Value |", "|---|---|---|"]
    for group, keys in order:
        for key in keys:
            if key in values:
                lines.append(f"| {group} | `{key}` | {values[key]} |")
    return lines, values


def short(component):
    return component.split(":", 1)[-1]


def main(evidence):
    ev = Path(evidence)
    out = ["# SonarQube results (generated by summarise.py)", ""]

    measures = load(ev / "main/measures.json")
    table, values = measure_table(measures)
    out += ["## Whole app (`helpdesk`)", ""] + table + [""]

    files = load(ev / "main/files.json")

    def num(f, key):
        for m in f.get("measures", []):
            if m["metric"] == key:
                return float(m["value"])
        return 0.0

    by_lang = collections.defaultdict(lambda: collections.Counter())
    for f in files:
        lang = f.get("language", "?")
        by_lang[lang]["files"] += 1
        for key in ("ncloc", "functions", "complexity", "cognitive_complexity", "lines_to_cover",
                    "uncovered_lines", "conditions_to_cover", "uncovered_conditions",
                    "bugs", "vulnerabilities", "code_smells"):
            by_lang[lang][key] += num(f, key)

    def cov(c):
        lines, conds = c["lines_to_cover"], c["conditions_to_cover"]
        if not lines + conds:
            return "n/a"
        covered = (lines - c["uncovered_lines"]) + (conds - c["uncovered_conditions"])
        return f"{100 * covered / (lines + conds):.1f}"

    out += ["### By language", "",
            "| Language | Files | ncloc | Functions | Cyclomatic | Cognitive | Bugs | Vulnerabilities | Code smells | Coverage % |",
            "|---|---|---|---|---|---|---|---|---|---|"]
    for lang, c in sorted(by_lang.items(), key=lambda kv: -kv[1]["ncloc"]):
        out.append(f"| {lang} | {c['files']} | {c['ncloc']:.0f} | {c['functions']:.0f} | {c['complexity']:.0f} | "
                   f"{c['cognitive_complexity']:.0f} | {c['bugs']:.0f} | {c['vulnerabilities']:.0f} | "
                   f"{c['code_smells']:.0f} | {cov(c)} |")
    out.append("")

    out += ["### Ten most complex files", "", "| File | ncloc | functions | cyclomatic | cognitive |", "|---|---|---|---|---|"]
    for f in sorted(files, key=lambda f: -num(f, "complexity"))[:10]:
        out.append(f"| `{f['path']}` | {num(f, 'ncloc'):.0f} | {num(f, 'functions'):.0f} | "
                   f"{num(f, 'complexity'):.0f} | {num(f, 'cognitive_complexity'):.0f} |")
    out.append("")
    out += ["### Files in the business-rule scope", "", "| File | ncloc | cyclomatic | cognitive | coverage % |", "|---|---|---|---|---|"]
    for f in files:
        if any(f["path"].endswith(s) for s in RULE_FUNCTIONS):
            out.append(f"| `{f['path']}` | {num(f, 'ncloc'):.0f} | {num(f, 'complexity'):.0f} | "
                       f"{num(f, 'cognitive_complexity'):.0f} | {num(f, 'coverage'):.1f} |")
    out.append("")

    issues = load(ev / "main/issues.json")
    by_quality = collections.Counter()
    by_rule = collections.Counter()
    for issue in issues:
        for impact in issue.get("impacts", []):
            by_quality[(impact["softwareQuality"], impact["severity"])] += 1
        by_rule[(issue["rule"], issue.get("message", "")[:0])] += 1
    out += [f"### Issues by software quality and severity ({len(issues)} issues)", "",
            "| Quality | Severity | Count |", "|---|---|---|"]
    for (quality, severity), count in sorted(by_quality.items()):
        out.append(f"| {quality} | {severity} | {count} |")
    out += ["", "### Most frequent rules", "", "| Rule | Count | Example |", "|---|---|---|"]
    examples = {}
    for issue in issues:
        examples.setdefault(issue["rule"], f"`{short(issue['component'])}:{issue.get('line', '')}` {issue.get('message', '')}")
    for (rule, _), count in by_rule.most_common(12):
        out.append(f"| `{rule}` | {count} | {examples[rule][:140]} |")
    out.append("")

    hotspots = load(ev / "main/hotspots.json")
    cats = collections.Counter((h.get("securityCategory"), h.get("vulnerabilityProbability")) for h in hotspots)
    out += [f"### Security hotspots ({len(hotspots)})", "", "| Category | Probability | Count |", "|---|---|---|"]
    for (cat, prob), count in cats.most_common():
        out.append(f"| {cat} | {prob} | {count} |")
    out.append("")

    gate = load(ev / "main/quality_gate.json")["projectStatus"]
    out += [f"Quality gate status: **{gate['status']}**", ""]
    for c in gate.get("conditions", []):
        out.append(f"* `{c['metricKey']}` {c['comparator']} {c.get('errorThreshold')}: actual {c.get('actualValue')} -> {c['status']}")
    out.append("")

    probe = load(ev / "complexity/issues.json")
    app_root = Path(__file__).resolve().parents[3]
    sources = {}

    def function_at(path, line):
        """Qualified name of the def on `line` (Sonar's messages omit it)."""
        if path not in sources:
            sources[path] = (app_root / path).read_text().splitlines()
        lines = sources[path]
        m = re.match(r"(\s*)def (\w+)", lines[line - 1])
        if not m:
            return f"(line {line})"
        if m.group(1):  # indented: find the enclosing class
            for previous in reversed(lines[: line - 1]):
                c = re.match(r"class (\w+)", previous)
                if c:
                    return f"{c.group(1)}.{m.group(2)}"
        return m.group(2)

    # both rules report on the def line, so the line identifies the function
    named = collections.defaultdict(dict)
    for issue in probe:
        msg = issue.get("message", "")
        key = (short(issue["component"]), issue.get("line"))
        if issue["rule"] == "python:FunctionComplexity":
            m = re.search(r"complexity of (\d+)", msg)
            if m:
                named[key]["cyclomatic"] = int(m.group(1))
        elif issue["rule"] == "python:S3776":
            m = re.search(r"from (\d+) to", msg)
            if m:
                named[key]["cognitive"] = int(m.group(1))
    for (path, line), data in named.items():
        data["name"] = function_at(path, line)
    out += ["## Per-function complexity of the business-rule files (`helpdesk-complexity`)", "",
            "Functions with cyclomatic complexity 1 are not reported by the rule and are omitted.", "",
            "| File | Line | Function | Cyclomatic (S1541) | Cognitive (S3776) | In rule scope |",
            "|---|---|---|---|---|---|"]
    for (path, line), data in sorted(named.items(), key=lambda kv: (kv[0][0], kv[0][1] or 0)):
        fname = path.rsplit("/", 1)[-1]
        wanted = RULE_FUNCTIONS.get(fname, [])
        bare = data["name"].rsplit(".", 1)[-1]
        in_scope = "yes" if wanted is None or bare in wanted else ""
        out.append(f"| `{fname}` | {line} | `{data['name']}` | {data.get('cyclomatic', 1)} | "
                   f"{data.get('cognitive', 0)} | {in_scope} |")
    out.append("")
    (ev / "summary.md").write_text("\n".join(out))
    print("\n".join(out))


if __name__ == "__main__":
    main(sys.argv[1])
